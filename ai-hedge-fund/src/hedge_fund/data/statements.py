BY_ID: dict[str, SeriesSpec] = {s.id: s for s in SERIES}


def catalog() -> list[dict[str, str]]:
    """The series, as the planner and the docs see them."""
    return [
        {"id": s.id, "label": s.label, "unit": s.unit, "description": s.description} for s in SERIES
    ]


def _finite(v: Any) -> float | None:
    try:
        f = float(v)
    except (TypeError, ValueError):
        return None
    return f if f == f and abs(f) != float("inf") else None


def _row(frame: Any, rows: tuple[str, ...], column: Any) -> float | None:
    for r in rows:
        if r in frame.index:
            return _finite(frame.at[r, column])
    return None


def build_table(
    frames: dict[str, Any],
    splits: Any = None,
    *,
    currency: str | None = None,
    end_date: date | None = None,
) -> dict[str, Any]:
    """Align three statements into one newest-first table. Pure: no fetching.

    A period is a column of the income statement; the other two statements are
    read at the same date when they have it, else left `None` for that year.
    """
    income = frames.get("income")
    if income is None or getattr(income, "empty", True):
        return {"error": "no income statement"}

    columns = sorted(income.columns, reverse=True)
    if end_date is not None:
        cutoff = end_date - timedelta(days=REPORTING_LAG_DAYS)
        columns = [c for c in columns if c.date() <= cutoff]
    if not columns:
        return {"error": "no period published before the as-of date"}

    series: dict[str, list[float | None]] = {}
    for spec in SERIES:
        frame = frames.get(spec.statement)
        values: list[float | None] = []
        for col in columns:
            if frame is None or getattr(frame, "empty", True) or col not in frame.columns:
                values.append(None)
            else:
                values.append(_row(frame, spec.rows, col))
        series[spec.id] = values

    if splits is not None and len(splits):
        adjusted: list[float | None] = []
        for col, v in zip(columns, series["shares"], strict=True):
            if v is None:
                adjusted.append(None)
                continue
            factor = 1.0
            for when, ratio in splits.items():
                if when.tz_localize(None) > col and ratio:
                    factor *= float(ratio)
            adjusted.append(v * factor)
        series["shares"] = adjusted

    return {
        "currency": currency,
        "frequency": "annual",
        "periods": [str(c.date()) for c in columns],
        "series": series,
        "source": "yfinance",
    }


def fetch_statements(ticker: str, end_date: date | None = None) -> dict[str, Any]:
    """The table for one company, cached, with its fetch recorded in provenance."""
    key = f"statements:{ticker.upper()}:{end_date or ''}"
    cached = _cache.get(DataCategory.FUNDAMENTALS, key)
    meta = new_meta(
        "statements", ticker.upper(), provider="yfinance", from_cache=cached is not None
    )
    if cached is not None:
        record(meta)
        return cached

    try:
        import yfinance as yf

        t = yf.Ticker(ticker)
        frames = {"income": t.income_stmt, "cashflow": t.cashflow, "balance": t.balance_sheet}
        currency = (t.info or {}).get("financialCurrency")
        table = build_table(frames, t.splits, currency=currency, end_date=end_date)
    except Exception as exc:  # noqa: BLE001 — a missing table must not stop a snapshot
        logger.debug("statements for %s failed: %s", ticker, exc)
        table = {"error": f"fetch failed: {type(exc).__name__}"}

    if "error" in table:
        meta.provider = None
        meta.error = table["error"]
    else:
        meta.checks = {
            "row_count": len(table["periods"]),
            "frequency": "annual",
            "currency": table["currency"],
        }
        _cache.set(DataCategory.FUNDAMENTALS, key, table)
    record(meta)
    return table
