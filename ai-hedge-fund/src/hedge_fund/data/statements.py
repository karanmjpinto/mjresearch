#: Accounts appear weeks after the year ends. Ninety days covers a 10-K's
#: filing deadline for every filer size, so a backtest never reads a year
#: before it was published.
REPORTING_LAG_DAYS = 90

#: Annual statements change four times a year at most.
_cache = TTLCache(ttls={DataCategory.FUNDAMENTALS: 6 * 3600})


