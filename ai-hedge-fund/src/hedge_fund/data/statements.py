"""Annual financial statements, as named series a plan can read.

Bridgewater's PAT spends most of its effort on what its builders call the
unglamorous part: mapping "output gap" to the right series, with the right
frequency, units and vintage, before anything is computed. The equivalent here
is small but has the same shape. `SERIES` is the catalog — each series has an
id, a label, a unit and the statement rows it may come from — and
`fetch_statements` turns a provider's three statements into one aligned table:

    {"currency": "USD", "frequency": "annual",
     "periods": ["2025-09-30", "2024-09-30", ...],      # newest first
     "series": {"revenue": [416.2e9, 391.0e9, ...], ...}}

Every series has one value per period, `None` where the provider had none, so
position i always means the same year. The screens drop missing values and
pair what is left, which is how a year can silently shift; this does not.

Three decisions worth knowing before reading a number off it:

- **Signs as reported.** Capex, buybacks and dividends are cash outflows and
  arrive negative. They are kept negative, and the metrics that read them say
  so, rather than flipping them here and leaving a reader to guess.
- **Share counts are split-adjusted.** The balance-sheet share count is as
  reported, so a 4:1 split reads as the company issuing three-quarters of
  itself. Each period is multiplied by the splits that came after it.
- **No look-ahead.** With an `end_date`, a period counts only if its accounts
  would have been public by then — period end plus `REPORTING_LAG_DAYS`.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
